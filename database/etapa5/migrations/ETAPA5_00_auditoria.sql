BEGIN READ ONLY;
WITH esperadas(tabla,columna) AS (VALUES ('usuarios','id'),
('usuarios','nombre'),
('usuarios','email'),
('usuarios','password'),
('usuarios','rol'),
('usuarios','activo'),
('peliculas','id'),
('peliculas','titulo'),
('peliculas','sinopsis'),
('peliculas','genero'),
('peliculas','duracion_minutos'),
('peliculas','clasificacion'),
('peliculas','fecha_estreno'),
('peliculas','imagen_url'),
('peliculas','estado'),
('salas','id'),
('salas','nombre'),
('salas','filas'),
('salas','columnas'),
('asientos','id'),
('asientos','fila'),
('asientos','numero'),
('asientos','sala_id'),
('funciones','id'),
('funciones','pelicula_id'),
('funciones','sala_id'),
('funciones','fecha_hora'),
('funciones','fecha_hora_fin'),
('funciones','precio'),
('funciones','cancelada'),
('productos','id'),
('productos','nombre'),
('productos','categoria'),
('productos','precio'),
('productos','activo'),
('ordenes','id'),
('ordenes','usuario_id'),
('ordenes','estado'),
('ordenes','total'),
('ordenes','fecha_creacion'),
('entradas','id'),
('entradas','orden_id'),
('entradas','funcion_id'),
('entradas','asiento_id'),
('entradas','precio_unitario'),
('detalle_productos','id'),
('detalle_productos','orden_id'),
('detalle_productos','producto_id'),
('detalle_productos','cantidad'),
('detalle_productos','precio_unitario'),
('notificaciones','id'),
('notificaciones','usuario_id'),
('notificaciones','mensaje'),
('notificaciones','leida'),
('notificaciones','fecha_creacion')),
cols AS (SELECT table_name, column_name,data_type,udt_name,is_nullable,column_default,is_identity,character_maximum_length,numeric_precision,numeric_scale FROM information_schema.columns WHERE table_schema='public' AND table_name IN ('usuarios', 'peliculas', 'salas', 'asientos', 'funciones', 'productos', 'ordenes', 'entradas', 'detalle_productos', 'notificaciones'))
SELECT jsonb_build_object(
 'base',current_database(), 'version',current_setting('server_version'), 'rol_auditoria',current_user,
 'faltantes',COALESCE((SELECT jsonb_agg(to_jsonb(e)) FROM esperadas e LEFT JOIN cols c ON c.table_name=e.tabla AND c.column_name=e.columna WHERE c.column_name IS NULL),'[]'::jsonb),
 'columnas',COALESCE((SELECT jsonb_agg(to_jsonb(c) ORDER BY table_name,column_name) FROM cols c),'[]'::jsonb),
 'tablas_rls',COALESCE((SELECT jsonb_agg(jsonb_build_object('tabla',c.relname,'rls',c.relrowsecurity,'force_rls',c.relforcerowsecurity,'owner',pg_get_userbyid(c.relowner),'anon_select',has_table_privilege('anon',c.oid,'SELECT'),'authenticated_select',has_table_privilege('authenticated',c.oid,'SELECT'),'anon_insert',has_table_privilege('anon',c.oid,'INSERT'),'authenticated_insert',has_table_privilege('authenticated',c.oid,'INSERT'),'anon_update',has_table_privilege('anon',c.oid,'UPDATE'),'authenticated_update',has_table_privilege('authenticated',c.oid,'UPDATE'),'anon_delete',has_table_privilege('anon',c.oid,'DELETE'),'authenticated_delete',has_table_privilege('authenticated',c.oid,'DELETE'))) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname IN ('usuarios', 'peliculas', 'salas', 'asientos', 'funciones', 'productos', 'ordenes', 'entradas', 'detalle_productos', 'notificaciones') AND c.relkind IN ('r','p')),'[]'::jsonb),
 'restricciones',COALESCE((SELECT jsonb_agg(jsonb_build_object('tabla',c.relname,'nombre',k.conname,'tipo',k.contype,'validada',k.convalidated,'definicion',pg_get_constraintdef(k.oid))) FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname IN ('usuarios', 'peliculas', 'salas', 'asientos', 'funciones', 'productos', 'ordenes', 'entradas', 'detalle_productos', 'notificaciones')),'[]'::jsonb),
 'indices',COALESCE((SELECT jsonb_agg(to_jsonb(i)) FROM pg_indexes i WHERE schemaname='public' AND tablename IN ('usuarios', 'peliculas', 'salas', 'asientos', 'funciones', 'productos', 'ordenes', 'entradas', 'detalle_productos', 'notificaciones')),'[]'::jsonb),
 'politicas',COALESCE((SELECT jsonb_agg(to_jsonb(q)) FROM pg_policies q WHERE schemaname='public' AND tablename IN ('usuarios', 'peliculas', 'salas', 'asientos', 'funciones', 'productos', 'ordenes', 'entradas', 'detalle_productos', 'notificaciones')),'[]'::jsonb),
 'extension_btree_gist',(SELECT n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace WHERE e.extname='btree_gist')
) AS auditoria;
COMMIT;
